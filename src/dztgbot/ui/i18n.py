"""Internationalization (i18n) module for DZTGBot UI.

Supports three UI languages:
- ``zh_TW``: Taiwan Traditional Chinese (繁體中文, default)
- ``en``: English
- ``zh_CN``: China Simplified Chinese (简体中文)

Note: Issue contents (Summary & Description) automatically generated by AI intake
are ALWAYS rendered in Simplified Chinese (简体中文) regardless of the UI language.
"""

from __future__ import annotations

from enum import Enum
from typing import Dict

class Language(str, Enum):
    ZH_TW = "zh_TW"
    EN = "en"
    ZH_CN = "zh_CN"

    @classmethod
    def normalize(cls, lang: str | None) -> Language:
        if not lang:
            return cls.ZH_TW
        code = lang.strip().lower().replace("-", "_")
        if code in ("zh_tw", "zh_hk", "zh_hant", "tw", "traditional"):
            return cls.ZH_TW
        if code in ("en", "en_us", "en_gb", "english"):
            return cls.EN
        if code in ("zh_cn", "zh_sg", "zh_hans", "cn", "simplified"):
            return cls.ZH_CN
        return cls.ZH_TW


