def get_text(key: str, lang: str | Language = Language.ZH_TW) -> str:
    """Resolve a localized UI string key for the target language."""
    language = Language.normalize(lang) if isinstance(lang, str) else lang
    entry = _STRINGS.get(key)
    if not entry:
        return key
    return entry.get(language, entry.get(Language.ZH_TW, key))
